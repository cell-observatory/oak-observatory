#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const source = path.resolve(__dirname, '../../..', 'herdr.lock');
const output = path.resolve(__dirname, '..', 'src', 'herdr-lock.ts');
const lock = JSON.parse(fs.readFileSync(source, 'utf8'));

if (!lock || typeof lock.version !== 'string' || typeof lock.protocol !== 'number' || !lock.assets || !lock.sha256) {
  throw new Error(`${source} is not a usable herdr.lock (needs version, protocol, assets, sha256)`);
}

fs.writeFileSync(
  output,
  `// Generated by scripts/gen-herdr-lock.js from the repository-root herdr.lock. Do not edit.\n` +
    `export const HERDR_LOCK = ${JSON.stringify(lock, null, 2)} as const;\n`
);
